// Drawn here in the same 256 grid, for what Phosphor lacks. `stroke` paths are drawn with the
// bold line width (24) instead of being filled.
const CUSTOM = {
  beard: {
    tint: ['M48,56V112c0,64,40,112,80,112s80-48,80-112V56c-8,40-32,64-56,64H104C80,120,56,96,48,56Z'],
    stroke: [
      'M48,56V112c0,64,40,112,80,112s80-48,80-112V56c-8,40-32,64-56,64H104C80,120,56,96,48,56Z',
      'M100,158c16,12,40,12,56,0',
    ],
  },
  mustache: {
    tint: ['M128,108C108,88,70,90,54,118c-8,14-20,22-36,16,10,32,54,44,84,22,12-8,20-14,26-20,6,6,14,12,26,20,30,22,74,10,84-22-16,6-28-2-36-16C186,90,148,88,128,108Z'],
    stroke: ['M128,108C108,88,70,90,54,118c-8,14-20,22-36,16,10,32,54,44,84,22,12-8,20-14,26-20,6,6,14,12,26,20,30,22,74,10,84-22-16,6-28-2-36-16C186,90,148,88,128,108Z'],
  },
};

const require = createRequire(import.meta.url);
const assets = join(dirname(require.resolve('@phosphor-icons/core')), '..', 'assets');
const paths = (svg: string, keep: (faded: boolean) => boolean) => [...svg.matchAll(/<path d="([^"]+)"([^>]*)\/>/g)]
  .filter(([, , attrs]) => keep(attrs.includes('opacity'))).map(([, d]) => d);

const icons: Record<string, { tint: string[]; line?: string[]; stroke?: string[] }> = {};
for (const name of PHOSPHOR) {
  const duotone = readFileSync(join(assets, 'duotone', `${name}-duotone.svg`), 'utf8');
  const bold = readFileSync(join(assets, 'bold', `${name}-bold.svg`), 'utf8');
  icons[name] = { tint: paths(duotone, (faded) => faded), line: paths(bold, () => true) };
}
Object.assign(icons, CUSTOM);

const out = new URL('../src/ui/iconPaths.ts', import.meta.url);
writeFileSync(out, `// Generated by tools/build-icons.ts (\`pnpm icons\`): do not edit by hand.
// Phosphor Icons (https://phosphoricons.com), MIT License, Copyright (c) 2023 Phosphor Icons.
// name → { tint: fill paths, line: outline paths (filled), stroke?: paths stroked with the line width }
export const ICON_PATHS = ${JSON.stringify(icons, null, 1)} satisfies Record<string, { tint: string[]; line?: string[]; stroke?: string[] }>;

/** Name of a pictogram of the game. */
export type IconName = keyof typeof ICON_PATHS;
`);
// The favicon of the game (the phone pages inline the same logo).
const { logoSvg } = await import('../src/ui/icons.ts');
writeFileSync(new URL('../public/favicon.svg', import.meta.url), logoSvg());
