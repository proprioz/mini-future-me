// Builds src/ui/iconPaths.ts (and public/favicon.svg), the pictograms of the game: `pnpm icons` after adding a name below.
// Each icon is Phosphor's duotone fill layer under its bold outline (https://phosphoricons.com, MIT),
// so the UI gets sticker-like pictograms (thick ink line, pastel fill) instead of emojis.
// Only the listed icons are copied, as plain path data: the game stays light, works offline, and the
// same paths serve inline SVG (DOM, phone pages) and Path2D (canvases).
